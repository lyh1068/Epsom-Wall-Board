#!/usr/bin/env python3
"""
Generate main/geo/runways.h from the OurAirports runways CSV.

Run by hand when the airport list changes; the header is committed, so the
build never needs the network:

    curl -o /tmp/runways.csv https://davidmegginson.github.io/ourairports-data/runways.csv
    python3 tools/make_runways.py --csv /tmp/runways.csv --out main/geo/runways.h

OurAirports data is public domain.
"""

import argparse
import csv
import pathlib
import sys

# ICAO ident -> label drawn on the radar. Everything within ~40 nm of Epsom
# with a hard runway long enough to matter.
AIRPORTS = {
    "EGLL": "LHR",
    "EGKK": "LGW",
    "EGLC": "LCY",
    "EGLF": "FAB",
    "EGKB": "BQH",
    "EGWU": "NHT",
}
MIN_LENGTH_FT = 4000


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--csv", required=True)
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    runways = []
    with open(args.csv, newline="", encoding="utf-8") as f:
        for row in csv.DictReader(f):
            ident = row["airport_ident"]
            if ident not in AIRPORTS or row["closed"] == "1":
                continue
            try:
                length = int(row["length_ft"] or 0)
                ends = [float(row[k]) for k in
                        ("le_latitude_deg", "le_longitude_deg", "he_latitude_deg", "he_longitude_deg")]
            except ValueError:
                continue  # missing coordinates
            if length < MIN_LENGTH_FT:
                continue
            runways.append((ident, row["le_ident"], row["he_ident"], ends))

    missing = sorted(set(AIRPORTS) - {r[0] for r in runways})
    if missing:
        sys.stderr.write("make_runways: no usable runways for %s\n" % ", ".join(missing))

    runways.sort()
    lines = [
        "/*",
        " * Generated by tools/make_runways.py from OurAirports runways.csv",
        " * (public domain). Do not edit by hand.",
        " */",
        "#pragma once",
        "",
        "typedef struct {",
        "    const char *label;      /* drawn next to the runway */",
        "    const char *name;       /* e.g. \"09L/27R\" */",
        "    double lat1, lon1, lat2, lon2;",
        "} runway_t;",
        "",
        "static const runway_t RUNWAYS[] = {",
    ]
    for ident, le, he, (la1, lo1, la2, lo2) in runways:
        lines.append('    { "%s", "%s/%s", %.6f, %.6f, %.6f, %.6f },  /* %s */'
                     % (AIRPORTS[ident], le, he, la1, lo1, la2, lo2, ident))
    lines += [
        "};",
        "",
        "#define RUNWAY_COUNT (sizeof(RUNWAYS) / sizeof(RUNWAYS[0]))",
        "",
    ]
    pathlib.Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print("wrote %d runways to %s" % (len(runways), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
