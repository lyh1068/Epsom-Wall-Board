#!/usr/bin/env python3
"""
Generate main/data/bus_map.h: a north-up street map around Epsom station from
OpenStreetMap, for the Buses page. Map data (c) OpenStreetMap contributors, ODbL;
the page shows that credit.

Run by hand; the header is committed, so the board never fetches map data:

    curl -A "your-app (contact)" -o /tmp/ways.json --data-urlencode 'data=[out:json][timeout:60];(
      way["highway"](around:480,51.3343,-0.2690);way["railway"="rail"](around:480,51.3343,-0.2690);
      way["railway"="platform"](around:480,51.3343,-0.2690););out geom tags;' https://overpass-api.de/api/interpreter
    python3 tools/make_bus_map.py --ways /tmp/ways.json --out main/data/bus_map.h
"""

import argparse
import math
import pathlib
import sys

CENTRE = (51.3343, -0.2690)     # Epsom station
SIZE = 620                      # px, square
SCALE = 0.9                     # px per metre: the 300 m circle is 270 px
MAX_LABELS = 12

# OSM highway/railway -> drawing class (see bus_map.h for the order).
CLASSES = {
    "trunk": 0, "primary": 0, "trunk_link": 0, "primary_link": 0,
    "secondary": 1, "tertiary": 1, "secondary_link": 1, "tertiary_link": 1,
    "residential": 2, "unclassified": 2, "pedestrian": 2, "living_street": 2,
    "service": 3,
    "footway": 4, "cycleway": 4, "path": 4, "steps": 4, "bridleway": 4,
}
CLASS_RAIL, CLASS_PLATFORM = 5, 6
LABEL_CLASSES = (0, 1, 2)


def project(lat, lon):
    mx = (lon - CENTRE[1]) * 111320 * math.cos(math.radians(CENTRE[0]))
    my = (lat - CENTRE[0]) * 110540
    return round(SIZE / 2 + mx * SCALE), round(SIZE / 2 - my * SCALE)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--ways", required=True, help="Overpass JSON with 'out geom'")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    import json
    els = json.loads(pathlib.Path(args.ways).read_text(encoding="utf-8"))["elements"]

    ways = []           # (class, [(x, y), ...], name)
    for e in els:
        t = e.get("tags", {})
        if t.get("railway") == "rail":
            cls = CLASS_RAIL
        elif t.get("railway") == "platform":
            cls = CLASS_PLATFORM
        elif t.get("highway") in CLASSES:
            cls = CLASSES[t["highway"]]
        else:
            continue
        pts = [project(g["lat"], g["lon"]) for g in e.get("geometry", [])]
        # Keep ways that come anywhere near the map; drawing clips the rest.
        if len(pts) < 2 or all(not (-50 <= x <= SIZE + 50 and -50 <= y <= SIZE + 50) for x, y in pts):
            continue
        ways.append((cls, pts, t.get("name", "")))

    # Draw minor first so major roads sit on top.
    order = [4, 3, 2, 1, 0, CLASS_PLATFORM, CLASS_RAIL]
    ways.sort(key=lambda w: order.index(w[0]))

    # One label per street name: midpoint of its longest way inside the map.
    best = {}
    for cls, pts, name in ways:
        if not name or cls not in LABEL_CLASSES:
            continue
        length = sum(math.dist(a, b) for a, b in zip(pts, pts[1:]))
        mid = pts[len(pts) // 2]
        if not (40 <= mid[0] <= SIZE - 120 and 20 <= mid[1] <= SIZE - 30):
            continue
        if name not in best or (cls, -length) < (best[name][0], -best[name][1]):
            best[name] = (cls, length, mid)
    labels = []
    for name, (cls, length, mid) in sorted(best.items(), key=lambda kv: (kv[1][0], -kv[1][1])):
        # Residential streets only if long: names go to the roads you navigate by.
        if length < (160 if cls == 2 else 60) or any(math.dist(mid, l[1]) < 70 for l in labels):
            continue
        labels.append((name, mid))
        if len(labels) == MAX_LABELS:
            break

    points, polys = [], []
    for cls, pts, _ in ways:
        polys.append((cls, len(points), len(pts)))
        points.extend(pts)

    out = [
        "/*",
        " * Generated by tools/make_bus_map.py from OpenStreetMap data",
        " * (c) OpenStreetMap contributors, ODbL. Do not edit by hand.",
        " * North up, centred on Epsom station, %.1f px per metre." % SCALE,
        " */",
        "#pragma once",
        "",
        "#include <stdint.h>",
        "",
        "#define BUS_MAP_SIZE %d" % SIZE,
        "#define BUS_MAP_SCALE %.2ff    /* px per metre */" % SCALE,
        "#define BUS_MAP_LAT %.6f" % CENTRE[0],
        "#define BUS_MAP_LON %.6f" % CENTRE[1],
        "",
        "/* Drawing classes, drawn in this order of the polys array (minor first). */",
        "enum { MAP_MAJOR, MAP_SECONDARY, MAP_MINOR, MAP_SERVICE, MAP_PATH, MAP_RAIL, MAP_PLATFORM };",
        "",
        "typedef struct {",
        "    uint8_t cls;",
        "    uint16_t first, count;   /* into BUS_MAP_POINTS */",
        "} bus_map_poly_t;",
        "",
        "static const int16_t BUS_MAP_POINTS[][2] = {",
    ]
    for i in range(0, len(points), 8):
        out.append("    " + " ".join("{ %d, %d }," % p for p in points[i:i + 8]))
    out += ["};", "", "static const bus_map_poly_t BUS_MAP_POLYS[] = {"]
    out += ["    { %d, %d, %d }," % p for p in polys]
    out += ["};", "#define BUS_MAP_POLY_COUNT ((int)(sizeof(BUS_MAP_POLYS) / sizeof(BUS_MAP_POLYS[0])))", "",
            "static const struct { const char *name; int16_t x, y; } BUS_MAP_LABELS[] = {"]
    out += ['    { "%s", %d, %d },' % (n, m[0], m[1]) for n, m in labels]
    out += ["};", "#define BUS_MAP_LABEL_COUNT ((int)(sizeof(BUS_MAP_LABELS) / sizeof(BUS_MAP_LABELS[0])))", ""]
    pathlib.Path(args.out).write_text("\n".join(out), encoding="utf-8")
    print("wrote %d ways, %d points, %d labels to %s" % (len(polys), len(points), len(labels), args.out))
    print("labels:", ", ".join(n for n, _ in labels))
    return 0


if __name__ == "__main__":
    sys.exit(main())
