#!/usr/bin/env python3
"""
Generate main/data/bus_stops.h: the TfL bus stops near Epsom station.

Run by hand when the area should change; the header is committed, so the
board does not search for stops at boot:

    curl -o /tmp/stops.json "https://api.tfl.gov.uk/StopPoint?lat=51.3343&lon=-0.2690&stopTypes=NaptanPublicBusCoachTram&radius=300"
    python3 tools/make_bus_stops.py --json /tmp/stops.json --out main/data/bus_stops.h

Stops TfL lists with no lines are Surrey County Council-only stops, which have
no TfL arrivals, so they are left out.
"""

import argparse
import json
import pathlib
import sys

MAX_STOPS = 8   # BUS_MAX_STOPS in bus_stops.h; the bus page is a 2x4 grid


def c_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--json", required=True, help="TfL /StopPoint search response")
    ap.add_argument("--out", required=True)
    args = ap.parse_args()

    stops = json.loads(pathlib.Path(args.json).read_text(encoding="utf-8"))["stopPoints"]
    stops = sorted((s for s in stops if s.get("lines")), key=lambda s: s["distance"])
    if len(stops) > MAX_STOPS:
        sys.stderr.write("make_bus_stops: %d stops, keeping the nearest %d\n" % (len(stops), MAX_STOPS))
        stops = stops[:MAX_STOPS]

    lines = [
        "/*",
        " * Generated by tools/make_bus_stops.py from a TfL StopPoint search",
        " * (TfL-served stops within 300 m of Epsom station). Do not edit by hand.",
        " */",
        "#pragma once",
        "",
        "#define BUS_MAX_STOPS %d" % MAX_STOPS,
        "",
        "typedef struct {",
        "    const char *naptan;     /* id for /StopPoint/{id}/Arrivals */",
        "    const char *name;",
        "    const char *letter;     /* the letter on the stop flag */",
        "    const char *routes;     /* TfL routes calling there */",
        "    int distance_m;         /* from the station */",
        "    float lat, lon;         /* for the map */",
        "} bus_stop_t;",
        "",
        "static const bus_stop_t BUS_STOPS[] = {",
    ]
    for s in stops:
        letter = s.get("stopLetter") or s.get("indicator", "").replace("Stop ", "")
        routes = " ".join(l["name"] for l in s["lines"])
        lines.append("    { %s, %s, %s, %s, %d, %.6ff, %.6ff }," % (c_str(s["naptanId"]), c_str(s["commonName"]),
                     c_str(letter), c_str(routes), round(s["distance"]), s["lat"], s["lon"]))
    lines += [
        "};",
        "",
        "#define BUS_STOP_COUNT ((int)(sizeof(BUS_STOPS) / sizeof(BUS_STOPS[0])))",
        "",
    ]
    pathlib.Path(args.out).write_text("\n".join(lines), encoding="utf-8")
    print("wrote %d stops to %s" % (len(stops), args.out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
